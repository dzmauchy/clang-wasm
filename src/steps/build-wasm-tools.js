import { fileURLToPath } from "node:url";
import { run, shellQuote } from "../utils/exec.js";

const wasmLldSourceDir = fileURLToPath(new URL("../../cmake/wasm-lld/", import.meta.url));
const wasmClangSourceDir = fileURLToPath(new URL("../../cmake/wasm-clang/", import.meta.url));

export function buildWasmBinaries(config) {
  console.log("\n--- Cross-Compiling Clang & LLD to Wasm ---");

  run(
    `
    emcmake cmake -G Ninja -B build-wasm -S llvm
      -DCMAKE_BUILD_TYPE=MinSizeRel
      -DCMAKE_C_FLAGS_MINSIZEREL="-Oz -DNDEBUG"
      -DCMAKE_CXX_FLAGS_MINSIZEREL="-Oz -DNDEBUG"
      -DLLVM_ENABLE_ASSERTIONS=OFF
      -DLLVM_ENABLE_PROJECTS="clang;lld"
      -DLLVM_EXTERNAL_PROJECTS="wasm-clang;wasm-lld"
      -DLLVM_EXTERNAL_WASM_CLANG_SOURCE_DIR=${shellQuote(wasmClangSourceDir)}
      -DLLVM_EXTERNAL_WASM_LLD_SOURCE_DIR=${shellQuote(wasmLldSourceDir)}
      -DLLD_BUILD_TOOLS=OFF
      -DLLVM_TARGETS_TO_BUILD="WebAssembly"
      -DLLVM_DEFAULT_TARGET_TRIPLE="wasm32-unknown-unknown"
      -DLLVM_NATIVE_TOOL_DIR="${config.nativeBinDir}"
      -DLLVM_ENABLE_THREADS=OFF
      -DLLVM_ENABLE_BACKTRACES=OFF
      -DLLVM_ENABLE_CRASH_OVERRIDES=OFF
      -DLLVM_ENABLE_LIBXML2=OFF
      -DLLVM_ENABLE_ZLIB=OFF
      -DLLVM_ENABLE_ZSTD=OFF
      -DLLVM_ENABLE_LIBPFM=OFF
      -DLLVM_ENABLE_PIC=OFF
      -DLLVM_ENABLE_UNWIND_TABLES=OFF
      -DLLVM_INSTALL_UTILS=OFF
      -DLLVM_ENABLE_PLUGINS=OFF
      -DLLVM_ENABLE_BINDINGS=OFF
      -DLLVM_ENABLE_TELEMETRY=OFF
      -DLLVM_INCLUDE_TESTS=OFF
      -DLLVM_INCLUDE_EXAMPLES=OFF
      -DLLVM_INCLUDE_BENCHMARKS=OFF
      -DLLVM_INCLUDE_DOCS=OFF
      -DLLVM_INCLUDE_UTILS=OFF
      -DLLVM_INCLUDE_RUNTIMES=OFF
      -DLLVM_BUILD_TOOLS=OFF
      -DLLVM_BUILD_UTILS=OFF
      -DLLVM_TOOL_LLVM_LTO_BUILD=OFF
      -DLLVM_TOOL_LLVM_LTO2_BUILD=OFF
      -DCLANG_ENABLE_STATIC_ANALYZER=OFF
      -DCLANG_ENABLE_OBJC_REWRITER=OFF
      -DCLANG_ENABLE_HLSL=OFF
      -DCLANG_ENABLE_LIBXML2=OFF
      -DCLANG_PLUGIN_SUPPORT=OFF
      -DCLANG_INCLUDE_TESTS=OFF
      -DCLANG_BUILD_TOOLS=OFF
      -DCLANG_TOOL_DRIVER_BUILD=OFF
      -DCLANG_TOOL_APINOTES_TEST_BUILD=OFF
      -DCLANG_TOOL_C_INDEX_TEST_BUILD=OFF
      -DCLANG_TOOL_CIR_LSP_SERVER_BUILD=OFF
      -DCLANG_TOOL_CIR_OPT_BUILD=OFF
      -DCLANG_TOOL_CIR_TRANSLATE_BUILD=OFF
      -DCLANG_TOOL_CLANG_CHECK_BUILD=OFF
      -DCLANG_TOOL_CLANG_DIFF_BUILD=OFF
      -DCLANG_TOOL_CLANG_EXTDEF_MAPPING_BUILD=OFF
      -DCLANG_TOOL_CLANG_FORMAT_BUILD=OFF
      -DCLANG_TOOL_CLANG_FUZZER_BUILD=OFF
      -DCLANG_TOOL_CLANG_IMPORT_TEST_BUILD=OFF
      -DCLANG_TOOL_CLANG_INSTALLAPI_BUILD=OFF
      -DCLANG_TOOL_CLANG_LINKER_WRAPPER_BUILD=OFF
      -DCLANG_TOOL_CLANG_NVLINK_WRAPPER_BUILD=OFF
      -DCLANG_TOOL_CLANG_OFFLOAD_BUNDLER_BUILD=OFF
      -DCLANG_TOOL_CLANG_REFACTOR_BUILD=OFF
      -DCLANG_TOOL_CLANG_REPL_BUILD=OFF
      -DCLANG_TOOL_CLANG_SCAN_DEPS_BUILD=OFF
      -DCLANG_TOOL_CLANG_SHLIB_BUILD=OFF
      -DCLANG_TOOL_CLANG_SSAF_ANALYZER_BUILD=OFF
      -DCLANG_TOOL_CLANG_SSAF_FORMAT_BUILD=OFF
      -DCLANG_TOOL_CLANG_SSAF_LINKER_BUILD=OFF
      -DCLANG_TOOL_CLANG_SYCL_LINKER_BUILD=OFF
      -DCLANG_TOOL_DIAGTOOL_BUILD=OFF
      -DCLANG_TOOL_LIBCLANG_BUILD=OFF
      -DCLANG_TOOL_OFFLOAD_ARCH_BUILD=OFF
      -DCLANG_TOOL_SCAN_BUILD_BUILD=OFF
      -DCLANG_TOOL_SCAN_BUILD_PY_BUILD=OFF
      -DCLANG_TOOL_SCAN_VIEW_BUILD=OFF
      -DDEFAULT_SYSROOT="/sysroot"
      -DCLANG_DEFAULT_CXX_STDLIB=""
      -DCLANG_DEFAULT_RTLIB="compiler-rt"
      -DCLANG_DEFAULT_LINKER="lld"
      -DCMAKE_CXX_FLAGS="${config.cxxFlags}"
      -DCMAKE_C_FLAGS="${config.cFlags}"
      -DCMAKE_EXE_LINKER_FLAGS="${config.exeLinkerFlags}"
    `,
    config.llvmDir,
    {},
    config.dryRun
  );

  run(
    `
    ninja -C build-wasm -j ${config.ninjaJobs}
      wasm-clang
      wasm-lld
    `,
    config.llvmDir,
    {},
    config.dryRun
  );
}
